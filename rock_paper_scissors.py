# Решение задачи "Камень, ножницы, бумага"

def solve_rock_paper_scissors():
    """
    Решает задачу на нахождение минимального количества раундов,
    которое мог проиграть второй игрок в игре "Камень, ножницы, бумага".
    
    Правила:
    - Камень побеждает ножницы
    - Ножницы побеждают бумагу
    - Бумага побеждает камень
    
    Второй игрок проигрывает когда:
    - Его камень встречает бумагу первого игрока
    - Его ножницы встречают камень первого игрока
    - Его бумага встречает ножницы первого игрока
    """
    
    # Читаем входные данные
    # Первая строка: r1, s1, p1 (камень, ножницы, бумага первого игрока)
    r1, s1, p1 = map(int, input().split())
    
    # Вторая строка: r2, s2, p2 (камень, ножницы, бумага второго игрока)
    r2, s2, p2 = map(int, input().split())
    
    # Вычисляем минимальное количество проигранных раундов для второго игрока
    # Камень второго игрока проигрывает бумаге первого
    losses_rock = min(r2, p1)
    
    # Ножницы второго игрока проигрывают камню первого
    losses_scissors = min(s2, r1)
    
    # Бумага второго игрока проигрывает ножницам первого
    losses_paper = min(p2, s1)
    
    # Общее количество проигранных раундов
    total_losses = losses_rock + losses_scissors + losses_paper
    
    return total_losses

if __name__ == "__main__":
    result = solve_rock_paper_scissors()
    print(result)