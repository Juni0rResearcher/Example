# Тестирование решения задачи "Камень, ножницы, бумага"

def solve_rock_paper_scissors_with_input(r1, s1, p1, r2, s2, p2):
    """
    Версия функции для тестирования с параметрами вместо input()
    """
    # Вычисляем минимальное количество проигранных раундов для второго игрока
    # Камень второго игрока проигрывает бумаге первого
    losses_rock = min(r2, p1)
    
    # Ножницы второго игрока проигрывают камню первого
    losses_scissors = min(s2, r1)
    
    # Бумага второго игрока проигрывает ножницам первого
    losses_paper = min(p2, s1)
    
    # Общее количество проигранных раундов
    total_losses = losses_rock + losses_scissors + losses_paper
    
    return total_losses

# Тестовые случаи
def run_tests():
    print("Запуск тестов...")
    
    # Тест 1: Простой случай
    # Первый игрок: 2 камня, 1 ножницы, 3 бумаги
    # Второй игрок: 1 камень, 2 ножниц, 3 бумаги
    result1 = solve_rock_paper_scissors_with_input(2, 1, 3, 1, 2, 3)
    print(f"Тест 1: {result1}")
    # Ожидаемый результат: min(1,3) + min(2,2) + min(3,1) = 1 + 2 + 1 = 4
    
    # Тест 2: Случай с нулями
    # Первый игрок: 5 камней, 0 ножниц, 0 бумаги
    # Второй игрок: 0 камней, 3 ножниц, 2 бумаги
    result2 = solve_rock_paper_scissors_with_input(5, 0, 0, 0, 3, 2)
    print(f"Тест 2: {result2}")
    # Ожидаемый результат: min(0,0) + min(3,5) + min(2,0) = 0 + 3 + 0 = 3
    
    # Тест 3: Равные значения
    # Первый игрок: 2 камня, 2 ножниц, 2 бумаги
    # Второй игрок: 2 камня, 2 ножниц, 2 бумаги
    result3 = solve_rock_paper_scissors_with_input(2, 2, 2, 2, 2, 2)
    print(f"Тест 3: {result3}")
    # Ожидаемый результат: min(2,2) + min(2,2) + min(2,2) = 2 + 2 + 2 = 6
    
    # Тест 4: Большие числа
    # Первый игрок: 1000000 камней, 500000 ножниц, 2000000 бумаги
    # Второй игрок: 800000 камней, 1200000 ножниц, 1500000 бумаги
    result4 = solve_rock_paper_scissors_with_input(1000000, 500000, 2000000, 800000, 1200000, 1500000)
    print(f"Тест 4: {result4}")
    # Ожидаемый результат: min(800000,2000000) + min(1200000,1000000) + min(1500000,500000) = 800000 + 1000000 + 500000 = 2300000
    
    print("Все тесты выполнены!")

if __name__ == "__main__":
    run_tests()